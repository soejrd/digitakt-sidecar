// I01 host-side policy test: the layout codec must keep the two directions
// separate, accept the R02 Digitakt fixture, preserve the Rytm, and refuse
// malformed/non-block endpoints. No hardware or Circle dependency.
//
//   c++ -std=c++17 -Wall -Wextra -I deps/sidecar-firmware/teensy/libraries/RytmHost \
//       tests/test_usb_layout_policy.cpp -o /tmp/test_usb_layout_policy
#include <cctype>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

#include "ob_block.h"

static std::vector<uint8_t> read_raw_capture(const char* path) {
  std::ifstream f(path);
  if (!f) { std::perror(path); std::exit(2); }
  std::vector<uint8_t> out;
  std::string line;
  bool in_raw = false;
  while (std::getline(f, line)) {
    if (line.find("raw configuration descriptor") != std::string::npos) { in_raw = true; continue; }
    if (!in_raw) continue;
    // "  0000: 09 02 07 ..." -> bytes after the colon
    const auto colon = line.find(':');
    if (colon == std::string::npos) continue;
    std::istringstream row(line.substr(colon + 1));
    std::string tok;
    while (row >> tok) {
      if (tok.size() != 2 || !std::isxdigit((unsigned char)tok[0]) || !std::isxdigit((unsigned char)tok[1])) break;
      out.push_back((uint8_t)std::strtoul(tok.c_str(), nullptr, 16));
    }
  }
  return out;
}

static void check(bool ok, const char* what) {
  if (!ok) { std::fprintf(stderr, "FAIL: %s\n", what); std::exit(1); }
}

