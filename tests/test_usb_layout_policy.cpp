int main(int argc, char** argv) {
  const char* capture = argc > 1 ? argv[1] : "evidence/r02-usb-descriptors-2026-10-26.txt";
  const std::vector<uint8_t> digitakt = read_raw_capture(capture);
  check(digitakt.size() == 263, "R02 raw configuration length");
  check(digitakt[0] == 0x09 && digitakt[1] == 0x02, "R02 configuration descriptor header");

  ob::Layout d{}, r{};
  check(ob::find_layout(digitakt.data(), (uint32_t)digitakt.size(), ob::kAlt, &d), "Digitakt layout");
  check(d.in_channels == 12 && d.in_bytes == 368, "Digitakt IN 12/368");
  check(d.out_channels == 2 && d.out_bytes == 88, "Digitakt OUT 2/88");
  check(d.in_bytes != d.out_bytes, "Digitakt directions stay distinct");
  check(ob::find_layout(kRytm, sizeof kRytm, ob::kAlt, &r), "Rytm layout");
  check(r.in_channels == 12 && r.out_channels == 12, "Rytm 12/12");
  check(r.in_bytes == 368 && r.out_bytes == 368, "Rytm 368/368");
  check(ob::channels_for(32) == 0, "32 B is not a block");
  check(ob::channels_for(60) == 1, "60 B is one channel");
  check(ob::channels_for(368) == 12, "368 B is twelve channels");
  check(ob::channels_for(88) == 2, "88 B is two channels");
  std::printf("USB layout policy: PASS (Digitakt 12/368 IN, 2/88 OUT; Rytm 12/12)\n");
  return 0;
}
